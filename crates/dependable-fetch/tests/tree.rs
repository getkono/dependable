/// Workspaces nest more than one deep — a `fuzz/` tree that itself vendors an
/// example workspace. The governing root is the *nearest* `[workspace]` ancestor,
/// so the innermost one wins, for the crate that declares it and for everything
/// below it.
#[test]
fn the_innermost_workspace_root_governs_when_workspaces_nest_twice() {
    let tmp = TempDir::new().unwrap();
    let dir = tmp.path();
    fs::write(
        dir.join("Cargo.toml"),
        r#"
[workspace]
resolver = "2"

[workspace.package]
version = "1.0.0"
"#,
    )
    .unwrap();
    let outer_member = dir.join("crates").join("a");
    fs::create_dir_all(&outer_member).unwrap();
    fs::write(
        outer_member.join("Cargo.toml"),
        r#"
[package]
name = "a"
version.workspace = true
"#,
    )
    .unwrap();
    let mid = dir.join("mid");
    fs::create_dir_all(&mid).unwrap();
    fs::write(
        mid.join("Cargo.toml"),
        r#"
[workspace]

[workspace.package]
version = "2.0.0"

[package]
name = "mid"
version.workspace = true
"#,
    )
    .unwrap();
    let inner = mid.join("inner");
    fs::create_dir_all(&inner).unwrap();
    fs::write(
        inner.join("Cargo.toml"),
        r#"
[workspace]

[workspace.package]
version = "3.0.0"

[package]
name = "inner"
version.workspace = true
"#,
    )
    .unwrap();
    let leaf = inner.join("crates").join("leaf");
    fs::create_dir_all(&leaf).unwrap();
    fs::write(
        leaf.join("Cargo.toml"),
        r#"
[package]
name = "leaf"
version.workspace = true
"#,
    )
    .unwrap();

    let built = build_workspace_graph(dir, &WorkspaceGraphOptions::default()).unwrap();
    assert_eq!(built.source, GraphSource::Manifests);
    let g = &built.graph;
    assert_eq!(version_of(g, "a"), Some("1.0.0"));
    // A manifest that is both a `[workspace]` and a `[package]` resolves against
    // itself, not against the root that contains it.
    assert_eq!(version_of(g, "mid"), Some("2.0.0"));
    assert_eq!(version_of(g, "inner"), Some("3.0.0"));
    assert_eq!(
        version_of(g, "leaf"),
        Some("3.0.0"),
        "the nearest [workspace] ancestor governs, not the outermost"
    );
}

/// `[workspace.dependencies]` is the second thing a root lends its members, and it
/// decides what a `dep.workspace = true` crate *is*. It is scoped exactly like
/// `[workspace.package]`: a nested workspace's crate takes its own root's
/// declaration, so a name that root vendors by path is a path crate, even though
/// the outer root declares the same shape of entry as a registry one.
///
/// The two names are deliberately different: one node carries one name, so a name
/// declared on both sides could not distinguish which root was consulted.
#[test]
fn a_nested_workspaces_crate_inherits_dependencies_from_its_own_root() {
    let tmp = TempDir::new().unwrap();
    let dir = tmp.path();
    fs::write(
        dir.join("Cargo.toml"),
        r#"
[workspace]
resolver = "2"

[workspace.dependencies]
outer-dep = "1"
nested-dep = "1"
"#,
    )
    .unwrap();
    let outer_member = dir.join("crates").join("outer");
    fs::create_dir_all(&outer_member).unwrap();
    fs::write(
        outer_member.join("Cargo.toml"),
        r#"
[package]
name = "outer"
version = "0.1.0"

[dependencies]
outer-dep.workspace = true
"#,
    )
    .unwrap();
    let nested = dir.join("nested");
    fs::create_dir_all(&nested).unwrap();
    fs::write(
        nested.join("Cargo.toml"),
        r#"
[workspace]

[workspace.dependencies]
nested-dep = { path = "../vendor/nested-dep" }

[package]
name = "nested"
version = "0.1.0"

[dependencies]
nested-dep.workspace = true
"#,
    )
    .unwrap();

    let built = build_workspace_graph(dir, &WorkspaceGraphOptions::default()).unwrap();
    assert_eq!(built.source, GraphSource::Manifests);
    let g = &built.graph;
    assert_eq!(kind_of(g, "outer-dep"), NodeKind::Registry);
    // The outer root declares `nested-dep = "1"` too, and consulting it would make
    // this a registry crate. The nested root is the one with authority here.
    assert_eq!(
        kind_of(g, "nested-dep"),
        NodeKind::Path,
        "a nested workspace's crate inherits from the nested root's declarations"
    );
}

/// Without a lockfile the graph is built from manifests alone, and a member's
/// `dep.workspace = true` says nothing about what the crate *is*. The root's declaration
/// does, and the root is already read here — so `centrally_declared` is classified from
/// what the root says it is, not from a guess that would make every inherited crate a
/// registry one (or, before inheritance existed at all, a local path).
#[test]
fn the_root_decides_what_an_inherited_dependency_is_in_the_shallow_graph() {
    let tmp = TempDir::new().unwrap();
    fs::write(
        tmp.path().join("Cargo.toml"),
        "[workspace]\nresolver = \"2\"\nmembers = [\"crates/a\"]\n\n[workspace.dependencies]\nserde = \"1\"\ncentrally_declared = { path = \"vendor/v\" }\n",
    )
    .unwrap();
    fs::create_dir_all(tmp.path().join("crates/a")).unwrap();
    fs::write(
        tmp.path().join("crates/a/Cargo.toml"),
        "[package]\nname = \"a\"\nversion = \"0.1.0\"\n\n[dependencies]\nserde.workspace = true\ncentrally_declared.workspace = true\nvendored = { path = \"../../vendor/v\" }\n",
    )
    .unwrap();

    let built = build_workspace_graph(tmp.path(), &WorkspaceGraphOptions::default()).unwrap();
    assert_eq!(built.source, GraphSource::Manifests);

    assert_eq!(kind_of(&built.graph, "serde"), NodeKind::Registry);
    // Declared centrally as a path, so it is a path crate wherever it is used — the case
    // a "an inherited entry is probably a registry crate" guess gets wrong.
    assert_eq!(kind_of(&built.graph, "centrally_declared"), NodeKind::Path);
    // And a member's own path entry, which never depended on the root at all.
    assert_eq!(kind_of(&built.graph, "vendored"), NodeKind::Path);
}

/// Without a lockfile a dependency's version is normally unknown, because a
/// manifest declares a constraint rather than a resolution. `= "1.0.200"` is the
/// exception: it admits exactly one release, so the manifest has already resolved
/// it and calling it unknown understates what was read.
///
/// Cargo's `"1"` beside it is the control. It looks concrete and is a caret range
/// over every 1.x release, which is why the rule cannot be "the string has three
/// numbers in it".
#[test]
fn an_exactly_pinned_dependency_reports_its_version_without_a_lockfile() {
    let tmp = TempDir::new().unwrap();
    fs::write(
        tmp.path().join("Cargo.toml"),
        "[workspace]\nresolver = \"2\"\nmembers = [\"crates/a\"]\n",
    )
    .unwrap();
    fs::create_dir_all(tmp.path().join("crates/a")).unwrap();
    fs::write(
        tmp.path().join("crates/a/Cargo.toml"),
        "[package]\nname = \"a\"\nversion = \"0.1.0\"\n\n\
         [dependencies]\n\
         serde = \"=1.0.200\"\n\
         regex = \"1\"\n\
         partial = \"=1.2\"\n\
         gitdep = { git = \"https://example.com/gitdep\", version = \"=1.2.3\" }\n\
         localdep = { path = \"../../vendor/v\", version = \"=4.5.6\" }\n",
    )
    .unwrap();

    let built = build_workspace_graph(tmp.path(), &WorkspaceGraphOptions::default()).unwrap();
    assert_eq!(built.source, GraphSource::Manifests);
    let g = &built.graph;

    assert_eq!(version_of(g, "serde"), Some("1.0.200"));
    // A caret range over every 1.x release names no single one of them.
    assert_eq!(version_of(g, "regex"), None);
    // `=1.2` is exact only to the minor: Cargo still accepts every 1.2.x patch.
    assert_eq!(version_of(g, "partial"), None);
    // Candidacy is `Item::is_checkable()`, which a git or path source fails
    // whatever version is written beside it. These are the crate at that location,
    // not the crate the registry publishes under that number.
    assert_eq!(version_of(g, "gitdep"), None);
    assert_eq!(version_of(g, "localdep"), None);
    assert_eq!(kind_of(g, "gitdep"), NodeKind::Git);
    assert_eq!(kind_of(g, "localdep"), NodeKind::Path);

    // The member's own version is read from `[package] version` and is untouched
    // by any of this.
    assert_eq!(version_of(g, "a"), Some("0.1.0"));
    assert!(
        g.nodes().iter().all(|n| n.version != Some(String::new())),
        "and never the empty string"
    );
}

/// A member's `dep.workspace = true` carries no version of its own; the root's
/// `[workspace.dependencies]` entry does, and inheritance is already resolved
/// before the graph is assembled. So a centrally pinned crate reports the pin the
/// root declared — the shape most workspaces that pin anything actually use.
#[test]
fn a_centrally_pinned_inherited_dependency_reports_the_roots_version() {
    let tmp = TempDir::new().unwrap();
    fs::write(
        tmp.path().join("Cargo.toml"),
        "[workspace]\nresolver = \"2\"\nmembers = [\"crates/a\"]\n\n\
         [workspace.dependencies]\n\
         serde = \"=1.0.200\"\n\
         regex = \"1\"\n",
    )
    .unwrap();
    fs::create_dir_all(tmp.path().join("crates/a")).unwrap();
    fs::write(
        tmp.path().join("crates/a/Cargo.toml"),
        "[package]\nname = \"a\"\nversion = \"0.1.0\"\n\n\
         [dependencies]\nserde.workspace = true\nregex.workspace = true\n",
    )
    .unwrap();

    let built = build_workspace_graph(tmp.path(), &WorkspaceGraphOptions::default()).unwrap();
    assert_eq!(built.source, GraphSource::Manifests);
    assert_eq!(version_of(&built.graph, "serde"), Some("1.0.200"));
    assert_eq!(version_of(&built.graph, "regex"), None);
}

/// One node per name across the whole workspace, so a version may only be carried
/// when every member that declares the crate agrees on it. Reporting the first
/// would make the graph depend on the order the directory walk found the members
/// in, and would state a version the other member's manifest contradicts.
#[test]
fn two_members_that_pin_one_crate_differently_resolve_to_nothing() {
    let tmp = TempDir::new().unwrap();
    fs::write(
        tmp.path().join("Cargo.toml"),
        "[workspace]\nresolver = \"2\"\nmembers = [\"crates/a\", \"crates/b\"]\n",
    )
    .unwrap();
    for (member, serde, agreed) in [("a", "=1.0.200", "=1.0.0"), ("b", "=1.0.201", "=1.0.0")] {
        fs::create_dir_all(tmp.path().join("crates").join(member)).unwrap();
        fs::write(
            tmp.path().join("crates").join(member).join("Cargo.toml"),
            format!(
                "[package]\nname = \"{member}\"\nversion = \"0.1.0\"\n\n\
                 [dependencies]\nserde = \"{serde}\"\nagreed = \"{agreed}\"\n"
            ),
        )
        .unwrap();
    }

    let built = build_workspace_graph(tmp.path(), &WorkspaceGraphOptions::default()).unwrap();
    assert_eq!(built.source, GraphSource::Manifests);
    assert_eq!(version_of(&built.graph, "serde"), None);
    // Agreement is not ambiguity: two members naming the same release still name it.
    assert_eq!(version_of(&built.graph, "agreed"), Some("1.0.0"));
}
